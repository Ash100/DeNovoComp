LIMITATIONS = (
    "Several limitations constrain these conclusions. The objective set is "
    "physicochemical, structural and synthesizability-oriented, and contains no docking, "
    "pharmacophore matching or trained activity model, so no part of the optimisation is "
    "directed at target binding; analogue design against a reference ligand provides only "
    "an indirect similarity proxy. Drug-likeness is evaluated from computed descriptors "
    "rather than trained pharmacokinetic models, and synthesizability from heuristics "
    "rather than routes, with SCScore and AiZynthFinder unavailable in the execution "
    "environment used. The run was performed on CPU-only hardware, which required the "
    "corpus to be subsampled and the prior to remain small; the quantitative results "
    "therefore characterise the pipeline at this configuration and do not bound its "
    "performance. Objectives are combined into a single scalar, which recovers no Pareto "
    "front, and the guaranteed decodability of SELFIES constrains the token distribution "
    "the model learns³⁰,⁵⁰. Each campaign comprises a single "
    "replicate at a fixed seed, the sweep covered three of the four campaigns, and no "
    "campaign was re-triaged at the lower intensity identified, so the inference that "
    "reduced intensity yields a better shortlist rests on diversity and alert data rather "
    "than on GO counts. No synthesis or assay was undertaken; computational triage narrows "
    "attention but does not establish activity.")

FUTURE = (
    "Four extensions follow directly from these limitations. Admitting target-based "
    "scoring components, such as docking scores, pharmacophore fit or trained activity "
    "models, would convert the system from property-directed to target-directed design, "
    "and the specification schema accommodates this without structural change. Integrating "
    "retrosynthetic route search as a terminal stage would replace estimated accessibility "
    "with proposed routes at the point where the additional cost is justified. An explicit "
    "multi-objective formulation would expose the Pareto front rather than resolving "
    "trade-offs implicitly. Prospective validation, through synthesis and assay of a GO "
    "shortlist, remains the decisive test of any computational prioritisation scheme.")

CONCLUSIONS = (
    "DeNovoComp is a specification-driven pipeline for RL-guided de novo molecular design "
    "in which design intent is declared rather than implemented and retained as a "
    "provenance record, feasibility is assessed and attributed before optimisation "
    "resources are committed, and synthesizability and applicability domain are treated as "
    "components of the objective and of the prioritisation rule. The campaigns reported "
    "here demonstrate substantial gains in specification compliance and the exact "
    "enforcement of categorical constraints. They also show that at the default "
    "optimisation intensity the pipeline's own diagnostics detect mode concentration, "
    "increased structural-alert incidence and an objective regressing beneath an improving "
    "aggregate, and that an intensity sweep identifies settings at which most of the "
    "attainable compliance is retained without these costs.")
